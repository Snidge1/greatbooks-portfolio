/* ============================================
   MODAL — Open & Close
   ============================================ */
function openAnalysis(id) {
  const data = analysisData[id];
  if (!data) return;

  const modal = document.getElementById('analysisModal');
  const content = document.getElementById('modalContent');

  let sectionsHTML = data.sections.map(s => `
    <h4>${s.heading}</h4>
    <p>${s.text}</p>
    <div class="modal-divider"></div>
  `).join('');

  content.innerHTML = `
    <div style="font-size:2.5rem; margin-bottom:1rem;">${data.emoji}</div>
    <h2>${data.title}</h2>
    <p class="modal-author">${data.author}</p>
    <span class="modal-lens">${data.lens}</span>
    <div class="modal-divider"></div>
    ${sectionsHTML}
  `;

  modal.classList.add('active');
  document.body.style.overflow = 'hidden';
}

function closeAnalysis() {
  const modal = document.getElementById('analysisModal');
  modal.classList.remove('active');
  document.body.style.overflow = '';
}

// Close on overlay click
document.getElementById('analysisModal').addEventListener('click', function(e) {
  if (e.target === this) closeAnalysis();
});

// Close on Escape key
document.addEventListener('keydown', e => {
  if (e.key === 'Escape') closeAnalysis();
});

