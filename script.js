/* ============================================
   PARTICLES
   ============================================ */
function createParticles() {
  const container = document.getElementById('particles');
  if (!container) return;
  const count = 50;
  for (let i = 0; i < count; i++) {
    const p = document.createElement('div');
    p.style.cssText = `
      position: absolute;
      width: ${Math.random() * 3 + 1}px;
      height: ${Math.random() * 3 + 1}px;
      background: rgba(212, 168, 83, ${Math.random() * 0.5 + 0.1});
      border-radius: 50%;
      left: ${Math.random() * 100}%;
      top: ${Math.random() * 100}%;
      animation: particleFloat ${Math.random() * 10 + 8}s ease-in-out infinite;
      animation-delay: ${Math.random() * 10}s;
    `;
    container.appendChild(p);
  }

  const style = document.createElement('style');
  style.textContent = `
    @keyframes particleFloat {
      0%, 100% { transform: translateY(0) translateX(0); opacity: 0.4; }
      25% { transform: translateY(-${Math.random() * 30 + 10}px) translateX(${Math.random() * 20 - 10}px); opacity: 0.8; }
      50% { transform: translateY(-${Math.random() * 50 + 20}px) translateX(${Math.random() * 30 - 15}px); opacity: 0.3; }
      75% { transform: translateY(-${Math.random() * 20 + 5}px) translateX(${Math.random() * 20 - 10}px); opacity: 0.7; }
    }
  `;
  document.head.appendChild(style);
}

/* ============================================
   INTERSECTION OBSERVER — Fade In
   ============================================ */
function initFadeIn() {
  const elements = document.querySelectorAll(
    '.analysis-card, .learning-node, .reflection-card, .profile-card, .favorite-layout, .work-summary-item'
  );
  elements.forEach(el => el.classList.add('fade-in'));

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });

  elements.forEach(el => observer.observe(el));
}

